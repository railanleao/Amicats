CREATE TABLE health_procedures
(
    id_health_procedure          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_cat                       INTEGER      NOT NULL REFERENCES cats (id_cat),

    type                         VARCHAR(20)  NOT NULL CHECK (type IN ('Vaccine', 'Deworming', 'Neutering')),

    name                         VARCHAR(150),

    status                       VARCHAR(20)  NOT NULL CHECK (status IN ('Scheduled', 'Completed', 'Cancelled')),

    scheduled_date               DATE         NOT NULL,

    completed_date               DATE,

    notes                        TEXT,

    cancel_reason                TEXT,

    id_previous_health_procedure INTEGER REFERENCES health_procedures (id_health_procedure),

    id_user_created_by           INTEGER      NOT NULL REFERENCES users (id_user),

    created_at                   TIMESTAMP    NOT NULL DEFAULT now(),

    updated_at                   TIMESTAMP    NOT NULL DEFAULT now(),

    CONSTRAINT chk_health_procedure_name
        CHECK (type = 'Neutering' OR name IS NOT NULL),

    CONSTRAINT chk_health_procedure_completed
        CHECK (status <> 'Completed' OR completed_date IS NOT NULL),

    CONSTRAINT chk_health_procedure_cancelled
        CHECK (status <> 'Cancelled' OR cancel_reason IS NOT NULL)
);

CREATE INDEX idx_health_procedures_cat
    ON health_procedures (id_cat, scheduled_date DESC);

CREATE INDEX idx_health_procedures_status
    ON health_procedures (status, scheduled_date);

CREATE INDEX idx_health_procedures_updated_at
    ON health_procedures (updated_at);

CREATE UNIQUE INDEX uq_health_procedures_scheduled_neutering
    ON health_procedures (id_cat)
    WHERE type = 'Neutering' AND status = 'Scheduled';

CREATE TRIGGER trg_health_procedures_updated_at
    BEFORE INSERT OR UPDATE
                         ON health_procedures
                         FOR EACH ROW
                         EXECUTE FUNCTION set_updated_at();

CREATE TABLE health_procedure_changes
(
    id_health_procedure_change INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_health_procedure        INTEGER     NOT NULL REFERENCES health_procedures (id_health_procedure),

    action                     VARCHAR(20) NOT NULL CHECK (action IN ('Created', 'Updated', 'Completed', 'Cancelled')),

    field                      VARCHAR(30) CHECK (field IN ('Name', 'ScheduledDate', 'Notes', 'CompletedDate',
                                                            'CancelReason')),

    old_value                  TEXT,

    new_value                  TEXT,

    id_user                    INTEGER     NOT NULL REFERENCES users (id_user),

    changed_at                 TIMESTAMP   NOT NULL DEFAULT now()
);

CREATE INDEX idx_health_procedure_changes_procedure
    ON health_procedure_changes (id_health_procedure, changed_at DESC);
