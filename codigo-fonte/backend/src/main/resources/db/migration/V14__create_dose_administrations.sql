CREATE TABLE dose_administrations
(
    id_dose_administration INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prescribed_medication INTEGER NOT NULL REFERENCES prescribed_medications (id_prescribed_medication),
    id_user_administered_by INTEGER NOT NULL REFERENCES users (id_user),
    client_operation_id UUID NOT NULL,
    administered_at TIMESTAMP(6) NOT NULL,
    recorded_at TIMESTAMP(6) NOT NULL,
    notes VARCHAR(2000),
    origin VARCHAR(20) NOT NULL CHECK (origin IN ('Online', 'OfflineSynced')),
    dosage VARCHAR(50) NOT NULL,
    route VARCHAR(20) NOT NULL CHECK (route IN ('Oral', 'Subcutaneous', 'Intramuscular',
                                              'Intravenous', 'Topical', 'Ophthalmic', 'Otic')),
    CONSTRAINT uk_dose_administrations_operation UNIQUE (client_operation_id),
    CONSTRAINT chk_dose_administrations_time CHECK (administered_at <= recorded_at)
);

CREATE INDEX idx_dose_administrations_medication_date
    ON dose_administrations (id_prescribed_medication, administered_at DESC, id_dose_administration DESC);