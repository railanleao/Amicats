CREATE TABLE external_attendances
(
    id_external_attendance   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cat                   INTEGER      NOT NULL REFERENCES cats (id_cat) ON DELETE CASCADE,
    partner_clinic           VARCHAR(150) NOT NULL,
    veterinarian             VARCHAR(150) NOT NULL,
    crmv                     VARCHAR(30)  NOT NULL,
    attendance_date          DATE         NOT NULL,
    diagnosis                TEXT         NOT NULL,
    attached_file            VARCHAR(255) NOT NULL,
    attachment_content_type  VARCHAR(100) NOT NULL,
    attachment_data          BYTEA        NOT NULL,
    created_at               TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE INDEX idx_external_attendances_cat_date
    ON external_attendances (id_cat, attendance_date DESC, created_at DESC);
