CREATE TABLE internal_medical_prescriptions
(
    id_internal_medical_prescription INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_cat                           INTEGER      NOT NULL REFERENCES cats (id_cat),

    id_user_vet                      INTEGER      NOT NULL REFERENCES users (id_user),

    status                           VARCHAR(20)  NOT NULL CHECK (status IN ('InTreatment', 'Completed', 'Cancelled')),

    title                            VARCHAR(200) NOT NULL,

    notes                            TEXT,

    created_at                       TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE INDEX idx_internal_medical_prescriptions_cat
    ON internal_medical_prescriptions (id_cat, created_at DESC);

CREATE TABLE prescribed_medications
(
    id_prescribed_medication         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_internal_medical_prescription INTEGER REFERENCES internal_medical_prescriptions (id_internal_medical_prescription),

    id_cat                           INTEGER     NOT NULL REFERENCES cats (id_cat),

    id_stock_item                    INTEGER     NOT NULL REFERENCES stock_items (id_stock_item),

    dosage                           VARCHAR(50) NOT NULL,

    route                            VARCHAR(20) NOT NULL CHECK (route IN ('Oral', 'Subcutaneous', 'Intramuscular',
                                                                           'Intravenous', 'Topical', 'Ophthalmic',
                                                                           'Otic')),

    interval_hours                   INTEGER     NOT NULL CHECK (interval_hours BETWEEN 1 AND 720),

    duration_days                    INTEGER     NOT NULL CHECK (duration_days BETWEEN 1 AND 365),

    start_date                       DATE        NOT NULL,

    end_date                         DATE        NOT NULL,

    status                           VARCHAR(20) NOT NULL CHECK (status IN ('Active', 'Completed', 'Cancelled')),

    cancelled_at                     TIMESTAMP,

    id_user_cancelled_by             INTEGER REFERENCES users (id_user),

    cancel_reason                    TEXT,

    created_at                       TIMESTAMP   NOT NULL DEFAULT now(),

    CONSTRAINT chk_prescribed_medication_has_origin
        CHECK (id_internal_medical_prescription IS NOT NULL),

    CONSTRAINT chk_prescribed_medication_period
        CHECK (end_date >= start_date)
);

CREATE INDEX idx_prescribed_medications_cat_status
    ON prescribed_medications (id_cat, status, end_date);
