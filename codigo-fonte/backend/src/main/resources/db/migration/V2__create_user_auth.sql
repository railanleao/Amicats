CREATE TABLE usuario_auth (
    id_user_auth INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL,

    email VARCHAR(150) NOT NULL,

    password_hash VARCHAR(255) NOT NULL,

    CONSTRAINT fk_usuario_auth_usuario
        FOREIGN KEY (user_id)
        REFERENCES user(id_user),

    CONSTRAINT uk_user_auth_user
        UNIQUE (user_id),

    CONSTRAINT uk_user_auth_email
        UNIQUE (email)
);