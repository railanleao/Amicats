CREATE TABLE cats
(
    id_cat              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name                VARCHAR(100) NOT NULL,

    room_id             INTEGER,

    sex                 VARCHAR(10),

    estimated_age       VARCHAR(50),

    coat                VARCHAR(100),

    microchip           VARCHAR(50),

    fiv_status          VARCHAR(20),

    felv_status         VARCHAR(20),

    pif_status          VARCHAR(20),

    neutered_status     VARCHAR(20),

    clinical_status     VARCHAR(30)  NOT NULL DEFAULT 'InTriage',

    health_notes        TEXT,

    rescue_date         DATE,

    rescue_location     VARCHAR(200),

    sponsor_name        VARCHAR(150),

    sponsor_phone       VARCHAR(20),

    sponsor_coverage    TEXT,

    created_by_user_id  INTEGER,

    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_cats_room
        FOREIGN KEY (room_id)
        REFERENCES rooms (id_room),

    CONSTRAINT fk_cats_created_by
        FOREIGN KEY (created_by_user_id)
        REFERENCES users (id_user),

    CONSTRAINT uk_cats_microchip UNIQUE (microchip)
);

CREATE TABLE cat_photos
(
    id_cat_photo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    cat_id       INTEGER      NOT NULL,

    storage_key  VARCHAR(255) NOT NULL,

    position     INTEGER      NOT NULL,

    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_cat_photos_cat
        FOREIGN KEY (cat_id)
        REFERENCES cats (id_cat)
);
