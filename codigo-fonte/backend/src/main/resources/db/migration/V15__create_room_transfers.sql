CREATE TABLE room_transfers
(
    id_room_transfer INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_cat           INTEGER      NOT NULL REFERENCES cats (id_cat),

    id_from_room     INTEGER REFERENCES rooms (id_room),

    id_to_room       INTEGER      NOT NULL REFERENCES rooms (id_room),

    reason           VARCHAR(500) NOT NULL,

    created_at       TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE INDEX idx_room_transfers_cat ON room_transfers (id_cat, created_at DESC);
