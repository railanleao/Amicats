CREATE TYPE sex AS ENUM (
    'Male',
    'Female'
);

CREATE TYPE age_group AS ENUM (
    'Kitten',
    'Young',
    'Adult',
    'Senior'
);

CREATE TYPE general_status AS ENUM (
    'UnderTreatment',
    'AvailableForAdoption',
    'InTriage',
    'Adopted',
    'TemporaryHome',
    'InClinic',
    'Deceased',
    'Missing'
);

CREATE TYPE health_status AS ENUM (
    'Healthy',
    'Fiv',
    'Felv',
    'FivFelv',
    'NotTested'
);

CREATE TYPE pif_result AS ENUM (
    'Positive',
    'Negative',
    'NotTested'
);

CREATE TYPE severity AS ENUM (
    'Low',
    'Medium',
    'High',
    'VeryHigh'
);

CREATE TYPE neutering_status AS ENUM (
    'Neutered',
    'NotNeutered',
    'Scheduled'
);

CREATE TABLE cats
(
    id_cat               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name                 VARCHAR(100)     NOT NULL,

    id_room              INTEGER REFERENCES rooms (id_room),

    sex                  sex,

    estimated_birth_date DATE,

    age_group            age_group,

    coat                 VARCHAR(100),

    weight_kg            DECIMAL(5, 2),

    characteristics      TEXT,

    general_status       general_status   NOT NULL,

    health_status        health_status    NOT NULL DEFAULT 'NotTested',

    fiv_felv_exam_date   DATE,

    pif_result           pif_result       NOT NULL DEFAULT 'NotTested',

    pif_exam_date        DATE,

    severity             severity,

    neutering_status     neutering_status,

    neutering_date       DATE,

    microchip            VARCHAR(50) UNIQUE,

    rescue_date          DATE,

    found_conditions     TEXT,

    sponsor_name         VARCHAR(150),

    sponsor_phone        VARCHAR(20),

    sponsor_funding      TEXT,

    id_user_creator      INTEGER          NOT NULL REFERENCES users (id_user),

    created_at           TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP
);
