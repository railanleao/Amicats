ALTER TABLE stock_items ADD COLUMN minimum_quantity NUMERIC(12,3) NOT NULL DEFAULT 10;
ALTER TABLE stock_items ADD CONSTRAINT chk_stock_minimum_quantity CHECK (minimum_quantity >= 0);

-- Historical applications stay NULL: no automatic retrospective debit.
ALTER TABLE dose_administrations ADD COLUMN consumed_quantity NUMERIC(12,3);
ALTER TABLE dose_administrations ADD COLUMN consumed_unit VARCHAR(30);
ALTER TABLE dose_administrations ADD COLUMN stock_balance_after NUMERIC(12,3);
ALTER TABLE dose_administrations ADD CONSTRAINT chk_dose_consumption CHECK (
  (consumed_quantity IS NULL AND consumed_unit IS NULL AND stock_balance_after IS NULL)
  OR (consumed_quantity IS NOT NULL AND consumed_quantity > 0
      AND consumed_unit IS NOT NULL AND length(trim(consumed_unit)) > 0 AND stock_balance_after IS NOT NULL)
);

CREATE TABLE stock_consumptions (
  id_stock_consumption INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_dose_administration INTEGER NOT NULL UNIQUE REFERENCES dose_administrations(id_dose_administration),
  id_stock_item INTEGER NOT NULL REFERENCES stock_items(id_stock_item),
  quantity NUMERIC(12,3) NOT NULL CHECK (quantity > 0),
  unit VARCHAR(30) NOT NULL,
  balance_before NUMERIC(12,3) NOT NULL,
  balance_after NUMERIC(12,3) NOT NULL,
  recorded_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT chk_stock_consumption_balance CHECK (balance_after = balance_before - quantity)
);
CREATE INDEX idx_stock_consumptions_item_date ON stock_consumptions(id_stock_item, recorded_at DESC);
CREATE INDEX idx_stock_medication_alerts ON stock_items(quantity, id_stock_item)
  WHERE lower(category) = 'medicamento' AND quantity <= minimum_quantity;
